//! Lattice-based candidates for gold-only positions with many unique moves.
//!
//! The best boards found have no two pieces orthogonally adjacent. This
//! takes every coset of every integer lattice of index 3, 4 or 5 that has no
//! unit vector (so no two of its squares are adjacent), fits it to 16 squares
//! by removing or adding squares (and, at index 4, swapping one or two), puts
//! the rabbits on the lowest squares, and scores the candidates in stages: the
//! 2-step count for all, the 3-step count for the best of those, then the full
//! count and a polish (hill climbing over single changes) for the very best.
//! Finally a silver rabbit is added on the best square for the legal variant.
//!
//! Usage: lattice [threads] [swaps]   (swaps: 0, 1 or 2 at index 4; default 1)

use std::collections::HashSet;
use std::sync::atomic::{AtomicUsize, Ordering};
use std::sync::Mutex;
use std::time::Instant;

use manymoves::search::{Rng, Variant, polish, valid};
use manymoves::{Board, Counter, GOLD, RABBIT, SILVER};

/// Board squares of every coset of every index-`n` lattice without unit vectors.
fn lattice_sets(n: i32) -> Vec<(String, u64)> {
    let mut out = Vec::new();
    for a in 1..=n {
        if n % a != 0 {
            continue;
        }
        let d = n / a;
        for b in 0..a {
            // Generated by (a, 0) and (b, d): (1, 0) is in it iff a == 1,
            // (0, 1) iff d == 1 and b == 0.
            if a == 1 || (d == 1 && b == 0) {
                continue;
            }
            for tx in 0..a {
                for ty in 0..d {
                    let mut mask = 0u64;
                    for y in 0..8i32 {
                        for x in 0..8i32 {
                            let (x0, y0) = (x - tx, y - ty);
                            if y0.rem_euclid(d) == 0 && (x0 - b * y0.div_euclid(d)).rem_euclid(a) == 0 {
                                mask |= 1 << (y * 8 + x);
                            }
                        }
                    }
                    out.push((format!("index {n} ({a},0),({b},{d}) + ({tx},{ty})"), mask));
                }
            }
        }
    }
    out
}

/// Every way to choose `k` squares of `from`, each added to `base`.
fn combos(from: u64, k: usize, base: u64, out: &mut Vec<u64>) {
    if k == 0 {
        out.push(base);
        return;
    }
    let mut rest = from;
    while rest.count_ones() as usize >= k {
        let sq = rest.trailing_zeros();
        rest &= rest - 1;
        combos(rest, k - 1, base | 1 << sq, out);
    }
}

/// Gold army on the squares of `mask` (16 squares): rabbits on the lowest
/// squares (never rank 8), the rest from strongest to weakest, alternating so
/// equal pieces aren't next to each other in the order.
fn assign(mask: u64) -> Option<Board> {
    let mut sqs: Vec<usize> = (0..64).filter(|&s| mask >> s & 1 != 0).collect();
    sqs.sort_by_key(|&s| (s / 8, s % 8));
    if sqs.len() != 16 || sqs[7] >= 56 {
        return None;
    }
    let mut b = Board::empty();
    for &s in &sqs[..8] {
        b.put(GOLD, RABBIT, s);
    }
    const ORDER: [usize; 8] = [5, 4, 3, 2, 1, 3, 2, 1]; // E M H D C H D C
    for (&s, &k) in sqs[8..].iter().zip(ORDER.iter()) {
        b.put(GOLD, k, s);
    }
    valid(&b, Variant::GoldOnly).then_some(b)
}

/// Scores `boards` with `steps`-step counts on `threads` threads; returns
/// the best `keep`, best first.
fn score(boards: &[Board], steps: u32, threads: usize, keep: usize) -> Vec<(usize, Board)> {
    let next = AtomicUsize::new(0);
    let results = Mutex::new(Vec::with_capacity(boards.len()));
    std::thread::scope(|s| {
        for _ in 0..threads {
            s.spawn(|| {
                let mut c = Counter::default();
                let mut local = Vec::new();
                loop {
                    let i = next.fetch_add(1, Ordering::Relaxed);
                    if i >= boards.len() {
                        break;
                    }
                    local.push((c.count_steps(&boards[i], steps), boards[i]));
                }
                results.lock().unwrap().extend(local);
            });
        }
    });
    let mut r = results.into_inner().unwrap();
    r.sort_by(|a, b| b.0.cmp(&a.0));
    r.truncate(keep);
    r
}

fn main() {
    let args: Vec<String> = std::env::args().collect();
    let threads: usize = args.get(1).map_or(8, |s| s.parse().unwrap());
    let swaps: usize = args.get(2).map_or(1, |s| s.parse().unwrap());
    let t0 = Instant::now();
    let mut masks = HashSet::new();
    for n in 3..=5 {
        for (name, base) in lattice_sets(n) {
            let size = base.count_ones() as usize;
            let mut v = Vec::new();
            if size > 16 {
                combos(base, size - 16, 0, &mut v);
                v.iter_mut().for_each(|m| *m = base & !*m);
            } else {
                combos(!base, 16 - size, base, &mut v);
                if size == 16 {
                    for k in 1..=swaps {
                        let mut removed = Vec::new();
                        combos(base, k, 0, &mut removed);
                        for r in removed {
                            combos(!base, k, base & !r, &mut v);
                        }
                    }
                }
            }
            println!("{name}: {size} squares, {} candidates", v.len());
            masks.extend(v);
        }
    }
    let boards: Vec<Board> = masks.into_iter().filter_map(assign).collect();
    println!("{} distinct valid candidates [{:.0}s]", boards.len(), t0.elapsed().as_secs_f64());

    let s2 = score(&boards, 2, threads, 50000);
    println!("2-step: best {} cutoff {} [{:.0}s]", s2[0].0, s2.last().unwrap().0, t0.elapsed().as_secs_f64());
    let b2: Vec<Board> = s2.iter().map(|x| x.1).collect();
    let s3 = score(&b2, 3, threads, 2000);
    println!("3-step: best {} cutoff {} [{:.0}s]", s3[0].0, s3.last().unwrap().0, t0.elapsed().as_secs_f64());
    let b3: Vec<Board> = s3.iter().map(|x| x.1).collect();
    let s4 = score(&b3, 4, threads, 16);
    println!("4-step: best {} [{:.0}s]", s4[0].0, t0.elapsed().as_secs_f64());
    std::fs::create_dir_all("results/lattice").unwrap();

    // Polish the best few in parallel.
    let polished = Mutex::new(Vec::new());
    std::thread::scope(|s| {
        for (i, &(n, b)) in s4.iter().enumerate().take(threads) {
            let polished = &polished;
            s.spawn(move || {
                let mut rng = Rng::new(i as u64 + 1);
                let mut c = Counter::default();
                let (pb, pn) = polish(b, Variant::GoldOnly, &mut rng, &mut c, |_, _| {});
                println!("candidate {i}: {n} -> polished {pn} [{:.0}s]", t0.elapsed().as_secs_f64());
                polished.lock().unwrap().push((pn, pb));
            });
        }
    });
    let mut polished = polished.into_inner().unwrap();
    polished.sort_by(|a, b| b.0.cmp(&a.0));
    for (n, b) in &polished {
        std::fs::write(format!("results/lattice/gold-{n}.txt"), format!("2g\n{}\n# {n} unique moves\n", b.diagram()))
            .unwrap();
    }
    let (gn, gb) = polished[0];
    println!("best gold-only: {gn}\n{}", gb.diagram());

    // Legal variant: add a silver rabbit wherever it costs least, then polish.
    let mut c = Counter::default();
    let mut best = (0, gb);
    for sq in 0..56 {
        if gb.all() >> sq & 1 == 0 {
            let mut q = gb;
            q.put(SILVER, RABBIT, sq);
            if valid(&q, Variant::Legal) {
                let n = c.count(&q);
                if n > best.0 {
                    best = (n, q);
                }
            }
        }
    }
    let mut rng = Rng::new(99);
    let (lb, ln) = polish(best.1, Variant::Legal, &mut rng, &mut c, |_, _| {});
    std::fs::write(format!("results/lattice/legal-{ln}.txt"), format!("2g\n{}\n# {ln} unique moves\n", lb.diagram()))
        .unwrap();
    println!("best legal: {} -> polished {ln}\n{}", best.0, lb.diagram());
}
